/// 最有力の次に前へ出す、よく使う表記の数。
const TOP: usize = 3;

/// よく使う名前の表記(よく使う順)。無ければ空。
pub fn common(reading: &str) -> &'static [&'static str] {
    COMMON.iter().find(|(r, _)| *r == reading).map(|(_, v)| *v).unwrap_or(&[])
}

/// 名前の部品を2つ(または3つ)つないで作った表記。読みが4文字以下か、部品の組み合わせで読み切れないときは作らない。
/// よく使う部品の表記から順に、最大 `max` 個。
pub fn composed(reading: &str, max: usize) -> Vec<String> {
    let chars: Vec<char> = reading.chars().collect();
    if chars.len() < 2 || chars.len() > 8 || !chars.iter().all(|c| ('ぁ'..='ゖ').contains(c)) {
        return vec![];
    }
    let parts_of = |s: &str| -> Vec<&'static str> {
        let mut v: Vec<&'static str> = vec![];
        for (r, ks) in PARTS {
            if *r == s {
                for k in *ks {
                    if !v.contains(k) {
                        v.push(k);
                    }
                }
            }
        }
        v
    };
    // 読みを2つ、または3つの部品に分ける分け方を全部試す(長い部品を先に)
    let mut splits: Vec<Vec<Vec<&'static str>>> = vec![];
    let n = chars.len();
    for i in 1..n {
        let (a, b): (String, String) = (chars[..i].iter().collect(), chars[i..].iter().collect());
        let (pa, pb) = (parts_of(&a), parts_of(&b));
        if !pa.is_empty() && !pb.is_empty() {
            splits.push(vec![pa.clone(), pb]);
        }
        for j in i + 1..n {
            let (b2, c): (String, String) = (chars[i..j].iter().collect(), chars[j..].iter().collect());
            let (pb2, pc) = (parts_of(&b2), parts_of(&c));
            if !pa.is_empty() && !pb2.is_empty() && !pc.is_empty() {
                splits.push(vec![pa.clone(), pb2, pc]);
            }
        }
    }
    // 部品の数が少ない分け方(まさ+ひろ)を、細かい分け方(ま+さ+ひろ)より先にする
    splits.sort_by_key(|s| s.len());
    let mut out: Vec<String> = vec![];
    // 各部品の「何番目の表記か」の合計が小さい順(よく使う表記どうしの組み合わせから)に並べる
    for split in &splits {
        let mut combos: Vec<(usize, String)> = vec![(0, String::new())];
        for part in split {
            let mut next = vec![];
            for (score, s) in &combos {
                for (i, k) in part.iter().enumerate() {
                    next.push((score + i, format!("{s}{k}")));
                }
            }
            next.sort_by_key(|x| x.0);
            next.truncate(max * 2);
            combos = next;
        }
        for (_, s) in combos {
            if !out.contains(&s) {
                out.push(s);
            }
        }
    }
    out.truncate(max);
    out
}

/// 辞書の候補 `cands` に、人名の候補を足す。
/// - よく使う表記は、最有力(先頭)の次に、よく使う順で並べる(すでに後ろにあれば前へ移す)。
/// - 部品から作った表記は、まだ無いものだけを最後に足す(辞書に無い名前でも必ず候補に出る)。
pub fn merge(reading: &str, cands: &mut Vec<String>, max_composed: usize) {
    let com = common(reading);
    if !com.is_empty() {
        let at = if cands.is_empty() { 0 } else { 1 };
        // 先頭がよく使う表記でないなら、先頭はそのまま(文脈や学習の結果を尊重)にして、その次に並べる
        // ふつうの言葉と同じ読み(めい=名、はな=花)もあるので、前へ出すのは上位3つまで。残りは無ければ足す。
        for k in com.iter().skip(TOP) {
            if !cands.iter().any(|c| c == k) {
                cands.push(k.to_string());
            }
        }
        let mut pos = at;
        for k in com.iter().take(TOP) {
            if cands.first().map(|f| f.as_str()) == Some(*k) {
                continue;
            }
            if let Some(i) = cands.iter().position(|c| c == k) {
                cands.remove(i);
            }
            let p = pos.min(cands.len());
            cands.insert(p, k.to_string());
            pos += 1;
        }
    }
    for s in composed(reading, max_composed) {
        if !cands.contains(&s) {
            cands.push(s);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn common_names_come_right_after_the_top() {
        let mut v = vec!["まさひろ".to_string(), "匡弘".to_string(), "正浩".to_string()];
        merge("まさひろ", &mut v, 10);
        assert_eq!(v[0], "まさひろ");
        assert_eq!(v[1], "正浩");
        assert_eq!(v[2], "雅弘");
        assert!(v.iter().filter(|c| *c == "正浩").count() == 1, "重ならない");
    }

    #[test]
    fn names_not_in_the_dictionary_are_composed() {
        // 辞書が空でも、部品から作る
        let mut v: Vec<String> = vec![];
        merge("たかのぶ", &mut v, 30);
        assert!(v.iter().any(|c| c == "隆信"), "{v:?}");
        assert!(composed("まさひろ", 40).iter().any(|c| c == "正浩"));
        assert!(composed("abc", 10).is_empty());
    }
}
