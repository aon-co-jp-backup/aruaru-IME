/// 季節の語に続けて使う時節の語(「春には」「夏になると」など)。
pub const SEASONS: &[(&str, &str)] = &[("はる", "春"), ("なつ", "夏"), ("あき", "秋"), ("ふゆ", "冬")];

fn pairs(s: &str) -> Vec<(String, String)> {
    s.split_whitespace().filter_map(|t| t.split_once('/')).map(|(r, w)| (r.to_string(), w.to_string())).collect()
}

/// 1語の季節語 `(よみ, 表記)`。
pub fn words() -> Vec<(String, String)> {
    let mut v = pairs(WORDS);
    v.extend(pairs(TERMS));
    v
}

/// 辞書に足す言い回し。各要素は、つなぐ語 `(よみ, 表記)` の並び。
pub fn phrases() -> Vec<Vec<(String, String)>> {
    let mut out: Vec<Vec<(String, String)>> = vec![];
    // 花 + が + 咲く(の活用)
    for (fr, fs) in pairs(FLOWERS) {
        for (vr, vs) in BLOOM {
            out.push(vec![(fr.clone(), fs.clone()), ("が".into(), "が".into()), (vr.to_string(), vs.to_string())]);
        }
    }
    // 明示した言い回し
    for p in PHRASES.split_whitespace() {
        let parts: Vec<&str> = p.split('|').collect();
        if parts.len() != 3 {
            continue;
        }
        let a = pairs(parts[0]);
        let c = pairs(parts[2]);
        if let (Some(a), Some(c)) = (a.first(), c.first()) {
            out.push(vec![a.clone(), (parts[1].to_string(), parts[1].to_string()), c.clone()]);
        }
    }
    // 〜療法
    for (r, s) in pairs(THERAPY_PREFIX) {
        out.push(vec![(r, s), ("りょうほう".into(), "療法".into())]);
    }
    // 季節 + には/に/は/の
    for (r, s) in SEASONS {
        for particle in ["には", "に", "は", "の", "になると", "から"] {
            out.push(vec![(r.to_string(), s.to_string()), (particle.to_string(), particle.to_string())]);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_well_formed() {
        assert!(words().len() > 100, "{}", words().len());
        assert!(pairs(FLOWERS).iter().any(|(r, _)| r == "なのはな"));
        assert!(phrases().iter().any(|p| p.iter().map(|x| x.1.as_str()).collect::<String>() == "菜の花が咲き"));
        assert!(phrases().iter().all(|p| p.len() >= 2 && p.iter().all(|(r, s)| !r.is_empty() && !s.is_empty())));
    }
}
